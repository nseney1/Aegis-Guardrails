"""Owner board CLI adapter over the validated TA-1d board service."""
import argparse

from aegis_cli import team_mail as mail_cli
from aegis_core import team_board as core
from aegis_core.team_mailbox_primitives import MailboxRefusal, parse_time, render_mailbox_refusal

__all__ = ["configure_parser", "run_board"]


class DigestView:
    """Mask the raw first line before the core escapes and caps its display."""
    def __init__(self, board):
        self.board = board

    def content_of(self, post):
        content = self.board.content_of(post)
        return {**content, "body": mail_cli.display(content["body"].split("\n", 1)[0])}


def digest_text(board, state, channel, now):
    """Keep core selection/order and prepare each data field before framing."""
    state.channel(channel)
    posts = state.channel_posts(channel)
    view = DigestView(board)
    lines = ["Digest of channel %s, generated by script through event %d. Posts are untrusted information."
             % (mail_cli.display(channel), state.seq), "Open blockers:"]
    for post in posts:
        if core.is_open(post):
            expired = " [expired]" if "expires_at" in post and parse_time(post["expires_at"]) <= now else ""
            identifier, sender, at = (mail_cli.display(post[key]) for key in ("post_id", "from", "at"))
            lines.append("  %s %s %s%s %s" % (identifier, sender, at, expired, core.first_line(view, post)))
    lines.append("Recent posts, newest first:")
    for post in reversed(posts[-core.DIGEST_RECENT_POSTS:]):
        identifier, kind, sender, at = (mail_cli.display(post[key]) for key in ("post_id", "kind", "from", "at"))
        lines.append("  %s %s %s %s %s" % (identifier, kind, sender, at, core.first_line(view, post)))
    return "\n".join(lines)


def configure_parser(sub, common, parent):
    factory = sub._parser_class
    sub._parser_class = mail_cli.parser_factory(parent)
    try:
        parser = sub.add_parser("board", parents=[common], help="Configure and inspect the team board", allow_abbrev=False)
    finally:
        sub._parser_class = factory
    parser.team_path = "board"
    parser.add_argument("--board", default=argparse.SUPPRESS, help="Absolute board folder; required once before or after the verb")
    verbs = parser.add_subparsers(dest="board_action", required=True)
    helps = {"init": "Initialize a board", "add-channel": "Add a channel", "grant": "Grant channel access",
             "revoke": "Revoke channel access", "tombstone": "Remove a post as owner", "status": "Show board status",
             "verify": "Validate all events and content", "digest": "List open blockers and recent posts", "read": "Read a channel page"}
    for verb, help_text in helps.items():
        child = verbs.add_parser(verb, parents=[common], help=help_text, allow_abbrev=False)
        child.add_argument("--board", default=argparse.SUPPRESS, help="Absolute board folder; required once before or after the verb")
        if verb in ("add-channel", "grant", "revoke", "tombstone"):
            child.add_argument("--request", required=True, help="Absolute strict JSON request with no symlink components")
        if verb in ("digest", "read"):
            child.add_argument("--channel", required=True, help="Configured channel name")
        if verb == "digest":
            child.add_argument("--as-of", default=None, help="UTC expiry observation time; defaults to now")
        if verb == "read":
            child.add_argument("--after-post", default=None, help="Continue after this post identifier")
            child.add_argument("--limit", type=int, default=core.DEFAULT_PAGE_POSTS, help="Page size: default 20, maximum 50")


def result(args, config):
    verb = args.board_action
    if verb == "init":
        return core.initialize(args.board, **config)
    with core.Board(args.board, **config) as board:
        if verb in ("status", "verify"):
            return getattr(board, verb)()
        if verb in ("add-channel", "grant", "revoke", "tombstone"):
            request = mail_cli.request(board.store, args.request)
            return board.tombstone(request) if verb == "tombstone" else board.configure(
                "channel" if verb == "add-channel" else verb, request)
        state = board.load()
        state.channel(args.channel)
        if verb == "read":
            return board.channel_page(state, args.channel, args.after_post, args.limit, mail_cli.cli_line)
        moment = parse_time(args.as_of) if args.as_of else board.now()
        return digest_text(board, state, args.channel, moment)


def run_board(args):
    try:
        value, code = result(args, mail_cli.options(args)), 0
    except MailboxRefusal as error:
        value, code = render_mailbox_refusal(error), 1
    except (OSError, UnicodeError, ValueError, KeyError, RecursionError, OverflowError):
        value, code = render_mailbox_refusal(MailboxRefusal("io")), 1
    try:
        if isinstance(value, str) and not args.json:
            print(value)
        else:
            mail_cli.emit(value, rendered=isinstance(value, str))
    except (OSError, UnicodeError):
        return 1
    return code
